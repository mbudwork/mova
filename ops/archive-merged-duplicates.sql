-- MOVA — 9 фраз из листа DUPLICATES_MERGED
--
-- НЕ ПРИМЕНЁН. Это решение по контенту, не по схеме.
--
-- Проверено в базе перед тем, как это писать:
--   • ни одна из девяти НЕ является primary ни в одном уроке — все девять
--     висят только как review_pool;
--   • phrase_progress по ним пуст (0 строк) — ни один пользователь их не
--     проходил, терять чей-то прогресс нечем;
--   • review_pool в движке v2 больше не читается: getLesson() фильтрует по
--     role='primary', а повторение строится динамически из phrase_progress.
-- То есть архивирование любой из девяти ничего в приложении не ломает.
--
-- Но воркбук делит их на две разные категории, и обращаться с ними
-- одинаково было бы ошибкой.
-- =============================================================================

begin;

-- ------------------------------------------------------- REMOVE (5 штук) ---
-- Точные дубли: тот же немецкий текст уже есть под другим ID. Здесь нечего
-- обсуждать — это техническая чистка, содержание не теряется.
--
--   P0171  Das ist noch nicht fertig.        -> канон P0159
--   P0362  Die Wand ist fertig.              -> канон P0326
--   P0378  Nicht einschalten!                -> канон P0204 (CORE)
--   P0379  Die Leitung steht unter Spannung. -> канон P0203 (CORE)
--   P0406  Kontrollier das Gefälle.          -> канон P0255 (Fliesenleger)
update phrases
   set verification_status = 'archived',
       notes = coalesce(notes || ' | ', '')
               || 'DUPLICATES_MERGED: точный дубль, канон — см. отчёт'
 where external_id in ('P0171','P0362','P0378','P0379','P0406');

-- Связи review_pool можно снять сразу же: строка архивная, держать её
-- в уроке незачем.
delete from lesson_phrases lp
 using phrases p
 where p.id = lp.phrase_id
   and p.external_id in ('P0171','P0362','P0378','P0379','P0406');

-- -------------------------------------------------------- MERGE (4 штуки) --
--   P0142  Prüf das nochmal.                 (prüfen / kontrollieren)
--   P0144  Das muss nochmal gemacht werden.  (актив / пассив)
--   P0149  So passt es.                      (нормально / подходит)
--   P0150  Das ist gut so.                   (см. P0149)
--
-- Это НЕ дубли. Воркбук помечает их как разные регистры одного смысла —
-- то есть материал для phrase_families, а не мусор. Если их просто
-- заархивировать, из курса пропадёт живая вариативность речи, ради которой
-- вся модель регистров и заводилась.
--
-- Поэтому здесь намеренно НЕТ update. Правильный следующий шаг — завести
-- по семейству на каждую пару и подвесить их как variants, тем же способом,
-- каким в миграции lessons заведено NV-N-CORE-001. Это отдельная задача:
-- нужно решить, какая из двух формулировок канон, а какая вариант, и на
-- каком уровне регистра — решение содержательное, за native reviewer.

-- ------------------------------------------------------------- ПРОВЕРКА ----
select verification_status::text, count(*)
  from phrases
 where external_id in ('P0142','P0144','P0149','P0150','P0171',
                       'P0362','P0378','P0379','P0406')
 group by 1;
